/**
 * Application entry point.
 *
 * Boot order matters. Anything that can fail is checked before a single
 * webhook can arrive, because the failure mode of a half-configured
 * compliance advisor is a meeting that looks screened and is not.
 *
 *   1. Node version, before importing the native addon
 *   2. Configuration
 *   3. Rule packs
 *   4. HTTP and WebSocket servers
 */

// ─── 1. Node version ────────────────────────────────────────────────────────
// @zoom/rtms uses N-API 9/10. On Node < 22 the import segfaults with a stack
// trace pointing at napi_module_register_by_symbol, which tells a developer
// nothing. Check first and say what is actually wrong.
const MAJOR = Number.parseInt(process.versions.node.split('.')[0], 10);
if (MAJOR < 22) {
  console.error(
    `\nNode.js ${process.versions.node} is too old.\n` +
      `@zoom/rtms requires Node.js >= 22.0.0 (24 LTS recommended).\n` +
      `Run "nvm use" to pick up the version pinned in .nvmrc.\n`,
  );
  process.exit(1);
}

import http from 'node:http';
import path from 'node:path';
import express from 'express';
import jwt from 'jsonwebtoken';
import { WebSocketServer } from 'ws';

// Generated by `prisma generate` into src/db/generated (see prisma/schema.prisma).
// Imported from the output path, not '@prisma/client': Prisma 7 drops the
// implicit node_modules/.prisma location, and a custom output makes the
// generated code visible rather than hidden inside node_modules.
import { PrismaClient } from './db/generated/index.js';

import { loadConfig, ConfigError } from './config.js';
import { loadPackDir, PackValidationError } from './compliance/packs.js';
import { handleWebhook } from './rtms/webhook.js';
import { createSessionManager } from './rtms/session.js';
import { createAlertHub } from './api/ws.js';
import { createAuditRouter } from './api/routes.js';
import { createAuditChain } from './compliance/audit.js';
import { createPipeline } from './compliance/pipeline.js';
import { createLlmClient } from './compliance/llm.js';
import { createTranscriptStore, createAuditStore } from './db/store.js';

const WEBHOOK_PATH = '/api/rtms/webhook';

// ─── 2. Configuration ───────────────────────────────────────────────────────
let config;
try {
  config = loadConfig(process.env);
} catch (err) {
  if (err instanceof ConfigError) {
    console.error(`\nConfiguration error: ${err.message}\n`);
    process.exit(1);
  }
  throw err;
}

// ─── 3. Rule packs ──────────────────────────────────────────────────────────
// Fail closed. Starting with a partially loaded pack would produce an audit
// log that claims coverage the app never had.
let packs;
try {
  packs = loadPackDir(path.resolve(config.rulePackDir));
} catch (err) {
  if (err instanceof PackValidationError) {
    console.error(`\nRule pack error in ${err.file}`);
    if (err.field) console.error(`  field: ${err.field}`);
    console.error(`  ${err.message}\n`);
    process.exit(1);
  }
  throw err;
}

if (!packs.has(config.rulePackId)) {
  console.error(
    `\nRULE_PACK_ID "${config.rulePackId}" was not found. Available: ${[...packs.keys()].join(', ')}\n`,
  );
  process.exit(1);
}

console.log(`Loaded ${packs.size} rule pack(s). Active: ${config.rulePackId}`);

// The RTMS SDK is imported after the version guard above, never at module top
// level, so the guard can actually run first.
const { default: rtms } = await import('@zoom/rtms');

// ─── Wiring ─────────────────────────────────────────────────────────────────
const prisma = new PrismaClient();
const transcripts = createTranscriptStore(prisma);
const auditChain = createAuditChain(createAuditStore(prisma));
const hub = createAlertHub({ jwtSecret: config.jwtSecret });
const llm = createLlmClient({
  baseUrl: config.llmBaseUrl,
  apiKey: config.llmApiKey,
  model: config.llmModel,
});

/** meetingId -> pipeline for the meeting currently in progress */
const pipelines = new Map();

function pipelineFor(meetingId) {
  if (pipelines.has(meetingId)) return pipelines.get(meetingId);

  const pipeline = createPipeline({
    meetingId,
    pack: packs.get(config.rulePackId),
    config,
    llm,
    hub,
    auditChain,
    // In a real deployment this comes from the meeting host's assignment. The
    // sample treats the Zoom host as the representative.
    representativeUserId: undefined,
  });

  pipelines.set(meetingId, pipeline);
  return pipeline;
}

function closePipeline(meetingId) {
  pipelines.get(meetingId)?.stop();
  pipelines.delete(meetingId);
  auditChain.forget(meetingId);
  hub.forget(meetingId);
}

const sessions = createSessionManager({
  clientFactory: () => new rtms.Client(),
  transcriptLanguage: rtms.TranscriptLanguage[config.transcriptLanguage],
  proxyUrl: config.rtmsProxyUrl,

  onSegment: (segment, { meetingId }) => {
    // Screen and broadcast first. Persistence must never delay an alert.
    pipelineFor(meetingId).onSegment(segment);

    transcripts
      .saveSegment(meetingId, segment)
      .catch((err) => console.error(`failed to persist segment: ${err.message}`));
  },

  audit: {
    open: (meetingId, reason) => {
      console.log(`RTMS joined for meeting ${meetingId} (reason ${reason})`);
      transcripts
        .ensureMeeting({ meetingId, rulePackVersion: config.rulePackId })
        .catch((err) => console.error(`failed to record meeting: ${err.message}`));
    },
    close: (meetingId, reason) => {
      console.log(`RTMS left meeting ${meetingId} (reason ${reason})`);
      transcripts.endMeeting(meetingId);
      closePipeline(meetingId);
    },
    coverageGap: (meetingId, timestamp) => {
      console.warn(`coverage gap in meeting ${meetingId} at ${timestamp}`);
      pipelineFor(meetingId)
        .recordCoverageGap(timestamp)
        .catch((err) => console.error(`failed to record coverage gap: ${err.message}`));
    },
    attendance: (meetingId, participants) => {
      console.log(`meeting ${meetingId} attendance: ${participants?.length ?? 0} participant(s)`);
    },
  },
});

// ─── 4. HTTP ────────────────────────────────────────────────────────────────
const app = express();

app.disable('x-powered-by');

/**
 * The webhook route takes the raw body, not parsed JSON.
 *
 * Zoom signs the exact bytes it sent. express.json() would hand us a parsed
 * object, and re-serializing it produces different bytes and a different
 * HMAC. express.raw() guarantees req.body is the original Buffer.
 *
 * The SDK also offers rtms.createWebhookHandler() for mounting on an existing
 * app. We verify here instead so the security-critical path stays in code
 * this repo tests directly.
 */
app.post(WEBHOOK_PATH, express.raw({ type: '*/*' }), (req, res) => {
  const { status, body, action } = handleWebhook({
    rawBody: req.body,
    headers: req.headers,
    secret: config.webhookSecret,
  });

  // Acknowledge before doing any work. Zoom retries on a slow response, and a
  // retry would be a second join for the same stream.
  res.status(status).json(body);

  if (action.type === 'stream_start') sessions.startStream(action.payload);
  if (action.type === 'stream_stop') sessions.stopStream(action.payload);
});

app.use(express.json());

app.get('/health', (_req, res) => {
  res.json({
    status: 'ok',
    activeStreams: sessions.activeStreamCount(),
    rulePack: config.rulePackId,
  });
});

/**
 * Issue a panel token.
 *
 * The Surface App calls this after in-client OAuth. The token is scoped to one
 * meeting and carries the role that decides whether alerts are visible.
 */
app.post('/api/panel/token', (req, res) => {
  const { meetingId, userId, role } = req.body ?? {};
  if (!meetingId || !userId) {
    return res.status(400).json({ error: 'meetingId and userId are required' });
  }

  const token = jwt.sign({ meetingId, userId, role: role ?? 'participant' }, config.jwtSecret, {
    expiresIn: '4h',
  });

  return res.json({ token });
});

const auditRouter = createAuditRouter({
  store: createAuditStore(prisma),
  jwtSecret: config.jwtSecret,
});
app.get('/api/meetings/:id/audit', (req, res) => auditRouter.handle(req, res));

app.use(express.static(path.resolve('web/dist')));

// ─── WebSocket ──────────────────────────────────────────────────────────────
const server = http.createServer(app);
const wss = new WebSocketServer({ server, path: '/ws' });

wss.on('connection', (socket, req) => {
  const token = new URL(req.url, config.publicUrl).searchParams.get('token');

  if (!hub.connect(socket, { token })) return;

  socket.on('message', (raw) => {
    try {
      hub.handleMessage(socket, JSON.parse(raw.toString('utf8')));
    } catch {
      hub.handleMessage(socket, {});
    }
  });

  socket.on('close', () => hub.disconnect(socket));
});

server.listen(config.port, () => {
  console.log(`Compliance advisor listening on :${config.port}`);
  console.log(`  webhook:  ${config.publicUrl}${WEBHOOK_PATH}`);
  console.log(`  zoom host: ${config.zoomHost}`);
});

// ─── Shutdown ───────────────────────────────────────────────────────────────
// Leaving streams explicitly means the audit chain closes with a reason rather
// than just stopping, which would be indistinguishable from a gap in coverage.
for (const signal of ['SIGTERM', 'SIGINT']) {
  process.on(signal, () => {
    console.log(`${signal} received, leaving ${sessions.activeStreamCount()} stream(s)`);
    sessions.shutdown();
    for (const meetingId of [...pipelines.keys()]) closePipeline(meetingId);
    server.close(() => prisma.$disconnect().finally(() => process.exit(0)));
  });
}
